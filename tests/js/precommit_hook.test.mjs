import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { install_hook } from "../../scripts/install_precommit_hook.mjs";

function repository(t) {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "kernel-wiki-hook-")));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const init = spawnSync("git", ["init", "-q", root], { encoding: "utf8" });
  assert.equal(init.status, 0, init.stderr);
  fs.mkdirSync(path.join(root, "scripts"));
  fs.mkdirSync(path.join(root, "data"));
  return root;
}

function script(root, name, status = 0) {
  fs.writeFileSync(path.join(root, "scripts", name), `process.stdout.write(${JSON.stringify(name + " ran\n")}); process.exitCode = ${status};\n`);
}

function runHook(root, hook) {
  return spawnSync(process.execPath, [hook], { cwd: root, encoding: "utf8" });
}

test("hook runs validation and only configured checks; repeated installation is safe", (t) => {
  const root = repository(t);
  script(root, "validate.mjs");
  const hook = install_hook(root);
  assert.equal(install_hook(root), hook);
  const result = runHook(root, hook);
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /validate\.mjs ran/);
  assert.doesNotMatch(result.stdout, /repo_size|check_dod/);
  assert.ok(fs.statSync(hook).mode & 0o100);
});

test("hook runs size and DoD checks when policies exist", (t) => {
  const root = repository(t);
  for (const name of ["validate.mjs", "repo_size_check.mjs", "check_dod_fixtures.mjs"]) script(root, name);
  for (const name of ["phase3-size-budget.yaml", "phase3-dod-fixtures.yaml"]) fs.writeFileSync(path.join(root, "data", name), "{}\n");
  const result = runHook(root, install_hook(root));
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /validate\.mjs ran[\s\S]*repo_size_check\.mjs ran[\s\S]*check_dod_fixtures\.mjs ran/);
});

test("hook propagates validation failures and stops subsequent checks", (t) => {
  const root = repository(t);
  script(root, "validate.mjs", 7);
  fs.writeFileSync(path.join(root, "data", "phase3-size-budget.yaml"), "{}\n");
  const result = runHook(root, install_hook(root));
  assert.equal(result.status, 7);
  assert.match(result.stderr, /validate\.mjs failed/);
  assert.doesNotMatch(result.stdout, /repo_size_check/);
});

test("installer protects unrelated hooks unless replacement is explicit", (t) => {
  const root = repository(t);
  const hook = path.join(root, ".git", "hooks", "pre-commit");
  fs.writeFileSync(hook, "#!/bin/sh\nexit 0\n");
  assert.throws(() => install_hook(root), /Existing pre-commit hook/);
  assert.equal(fs.readFileSync(hook, "utf8"), "#!/bin/sh\nexit 0\n");
  assert.equal(install_hook(root, { force: true }), hook);
  assert.match(fs.readFileSync(hook, "utf8"), /Generated by kernel-wiki/);
});

test("installer resolves hooks for a linked Git worktree", (t) => {
  const root = repository(t);
  const commit = spawnSync("git", ["-c", "user.name=Hook Test", "-c", "user.email=hook@example.invalid", "commit", "--allow-empty", "--no-verify", "-qm", "fixture"], { cwd: root, encoding: "utf8" });
  assert.equal(commit.status, 0, commit.stderr);
  const linked = path.join(root, "linked");
  const worktree = spawnSync("git", ["worktree", "add", "-q", "--detach", linked], { cwd: root, encoding: "utf8" });
  assert.equal(worktree.status, 0, worktree.stderr);
  assert.equal(install_hook(linked), path.join(root, ".git", "hooks", "pre-commit"));
});
