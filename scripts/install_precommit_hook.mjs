#!/usr/bin/env node
/** Install the Node.js corpus checks as a Git pre-commit hook. */
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { pathToFileURL } from "node:url";
import { WIKI_ROOT } from "./_root.mjs";

const MARKER = "// Generated by kernel-wiki/scripts/install_precommit_hook.mjs";
export const HOOK_SOURCE = `#!/usr/bin/env node
${MARKER}
const { spawnSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");
const git = spawnSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8" });
if (git.error || git.status !== 0) {
  console.error("[pre-commit] Cannot resolve the repository root");
  process.exit(2);
}
const root = git.stdout.trim();
const checks = [
  ["validate.mjs", null],
  ["repo_size_check.mjs", "data/phase3-size-budget.yaml"],
  ["check_dod_fixtures.mjs", "data/phase3-dod-fixtures.yaml"],
];
for (const [script, condition] of checks) {
  if (condition && !fs.existsSync(path.join(root, condition))) continue;
  console.log("[pre-commit] " + script);
  const result = spawnSync(process.execPath, [path.join(root, "scripts", script)], {
    cwd: root, stdio: "inherit",
  });
  if (result.error || result.status !== 0) {
    console.error("[pre-commit] " + script + " failed");
    process.exit(result.status || 1);
  }
}
`;

export function install_hook(root = WIKI_ROOT, { force = false } = {}) {
  const git = spawnSync("git", ["rev-parse", "--path-format=absolute", "--git-path", "hooks"], {
    cwd: root, encoding: "utf8",
  });
  if (git.error || git.status !== 0) {
    throw new Error(`Cannot locate Git hooks: ${git.error?.message || git.stderr.trim()}`);
  }
  const hook = path.join(git.stdout.trim(), "pre-commit");
  if (fs.existsSync(hook) && !force && !fs.readFileSync(hook, "utf8").includes(MARKER)) {
    throw new Error(`Existing pre-commit hook at ${hook}; use --force to replace it.`);
  }
  fs.mkdirSync(path.dirname(hook), { recursive: true });
  fs.writeFileSync(hook, HOOK_SOURCE, { mode: 0o755 });
  fs.chmodSync(hook, 0o755);
  return hook;
}

export function main(args = process.argv.slice(2)) {
  if (args.includes("--help") || args.includes("-h")) {
    console.log("Usage: node scripts/install_precommit_hook.mjs [--force]");
    return 0;
  }
  if (args.some((arg) => arg !== "--force")) {
    console.error("Usage: node scripts/install_precommit_hook.mjs [--force]");
    return 2;
  }
  try {
    console.log(`Installed pre-commit hook at ${install_hook(WIKI_ROOT, { force: args.includes("--force") })}`);
    return 0;
  } catch (error) {
    console.error(`ERROR: ${error.message}`);
    return 2;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  process.exitCode = main();
}
